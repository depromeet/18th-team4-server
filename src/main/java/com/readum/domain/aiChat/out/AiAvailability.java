package com.readum.domain.aiChat.out;

import java.util.Set;

/**
 * AI 공급자 기능별 가용 상태 조회. 공급자가 장애로 판정돼 차단된 동안 새 외부 호출을 시작하지 않게 한다.
 *
 * <p><b>왜 기능(Capability)별인가.</b> 우리는 OpenAI 호출을 기능마다 다른 프로젝트로 나눠 보낸다
 * (프로젝트 하나 = 키 하나 + 분당 한도 하나). 한 프로젝트가 한도 소진·결제 문제·키 설정 오류로 막혀도
 * 다른 프로젝트는 멀쩡하므로, 장애 상태도 프로젝트(= 기능) 단위로 따로 센다.
 * 보호 규칙(무엇을 실패로 셀지, 언제 차단할지)은 다섯 기능이 공유한다.
 *
 * <p><b>차단 중에는 예외가 없다.</b> 차단된 기능에는 사용자 요청도, 이미 쌓여 있던 큐 작업도 외부 호출을
 * 시작하지 않는다 — 차단 시간이 지났더라도 마찬가지다. 그 시각은 "이제 복구를 확인해 볼 때" 라는 뜻이고,
 * 확인은 <b>전용 복구 확인 스케줄러</b>가 자기 호출로만 한다. 그래서 이 포트에는 복구 확인을 위한 자리가 없다 —
 * 사용자 요청을 복구에 쓰면, 아직 고쳐졌는지 모르는 공급자에 사용자가 기다리는 호출을 내보내는 셈이 된다.
 *
 * <p>상태는 여러 서버 프로세스가 함께 보아야 해서 Redis 에 둔다. 조회가 실패하면(Redis 장애)
 * 상태를 모르는 것이므로 <b>새 외부 호출은 받지 않는다</b> — 게이트(속도 맞추기)의 통과-우선과 반대 방향이다.
 * 게이트가 통과시키는 것은 "빨리 보내도 되는가" 이고, 여기서 막는 것은 "지금 보내면 확실히 실패하는가" 이기 때문이다.
 */
public interface AiAvailability {

    /**
     * 보호 단위. OpenAI 프로젝트 하나와 1:1 로 대응한다.
     *
     * <p>{@link #dependencies()} 는 "그 기능을 수행하려면 반드시 성공해야 하는 다른 기능" 이다.
     * 채팅은 보내기 전에 입력 검토(moderation)를 거치고, 감상문은 생성 결과를 출력 검토에 통과시켜야 하므로
     * 둘 다 {@link #MODERATION} 에 기댄다. 의존 기능이 막혀 있으면 본 기능도 시작하지 않는다 —
     * 어차피 중간에 막힐 호출로 한도와 비용을 쓰지 않기 위해서다.
     *
     * <p>의존이 회복되어도 그것이 본 기능 자신의 차단을 풀지는 않는다 — 감상문 프로젝트가 막혀 있으면
     * 그 차단은 감상문의 복구 확인이 풀어야 한다. 다만 의존 장애 동안 쌓인 적체의 우선권은 지켜야 하므로,
     * 회복 시 <b>정상인</b> 큐를 적체 처리 상태로 밀어 넣는 반대 방향의 관계가 따로 있다
     * ({@link Capability#queuedDependents()}).
     */
    enum Capability {
        CHAT,
        MODERATION,
        SUMMARY,
        CONTEXT_SUMMARY,
        TITLE;

        /** 이 기능이 한 번 수행되는 동안 반드시 함께 성공해야 하는 다른 기능들. */
        public Set<Capability> dependencies() {
            return switch (this) {
                case CHAT, SUMMARY -> Set.of(MODERATION);
                case MODERATION, CONTEXT_SUMMARY, TITLE -> Set.of();
            };
        }

        /**
         * 작업 큐가 처리하는 기능인가. 큐가 있는 기능은 차단이 풀린 뒤 쌓인 작업을 먼저 비우고,
         * 다 비운 뒤에야 신규 접수를 다시 받는다(적체가 있는 동안 신규 접수를 받으면 복구가 끝나지 않는다).
         */
        public boolean queued() {
            return this == SUMMARY || this == CONTEXT_SUMMARY;
        }

        /**
         * 이 기능에 기대는 기능들 중 큐를 가진 것 — {@link #dependencies()} 의 반대 방향이다.
         *
         * <p>왜 필요한가: 검토가 막혀 있는 동안 감상문 작업은 계속 쌓이지만 감상문 <b>자체</b>의 상태는 정상이다.
         * 검토가 살아나는 순간 아무 일도 없었던 것처럼 신규 접수가 열리면, 그때 쌓인 적체보다 새 요청이 먼저 들어간다 —
         * "기존 큐를 비운 뒤에 신규 접수" 라는 규칙이 의존 장애에서만 조용히 깨지는 셈이다.
         * 그래서 의존 기능이 복구될 때 이쪽 큐를 적체 처리 상태로 함께 밀어 넣는다.
         *
         * <p><b>스스로 차단된 큐는 건드리지 않는다.</b> 감상문이 자기 이유로 막혀 있으면 그 차단은 감상문의
         * 복구 확인이 풀어야 한다 — 여기서 덮으면 그 기능의 차단·확인 진행 상황이 지워지고, 아직 죽어 있는
         * 프로젝트로 작업이 나간다. 그래서 이 밀어 넣기는 <b>정상(CLOSED)인 큐에만</b> 적용된다.
         */
        public Set<Capability> queuedDependents() {
            return this == MODERATION ? Set.of(SUMMARY) : Set.of();
        }
    }

    /**
     * 새 요청·새 작업을 받아도 되는지 확인한다. 차단 중이거나, 아직 비우지 못한 적체가 있거나,
     * 상태를 확인할 수 없으면 {@link com.readum.domain.aiChat.exception.AiDependencyUnavailableException} 을 던진다.
     * 의존 기능({@link Capability#dependencies()})도 함께 본다.
     *
     * <p>부수 효과가 없는 <b>확인</b>이다 — 호출 권한을 잡아 두지 않으므로, 확인과 실제 호출 사이에
     * 상태가 바뀔 수 있다. 그래서 실제 호출 직전에 한 번 더 확인하는 지점이 따로 있다(모델 보호 계층).
     */
    void requireAvailable(Capability capability);

    /**
     * 큐 워커가 작업을 선점하기 전에 묻는다 — 지금 이 기능의 작업을 처리해도 되는가.
     * 차단 중이거나 상태를 확인할 수 없으면 {@code false} (선점하지 않는다 → 헛선점·시도 횟수 소진 방지).
     * 차단이 풀린 뒤 쌓인 작업을 비우는 동안에는 {@code true} 다 — 그때 막아야 하는 것은 신규 접수뿐이다.
     */
    boolean canProcess(Capability capability);

    /**
     * 이 기능의 큐에 처리할 작업이 하나도 남지 않았음을 알린다 — 적체를 다 비웠으니 신규 접수를 다시 받는다.
     *
     * <p><b>무트래픽 복귀의 마지막 한 걸음이다.</b> 복구 확인이 성공하면 큐 있는 기능은 적체 처리 상태가 되고,
     * 워커 디스패처는 큐가 비어 있어도 주기마다 돌아 이것을 부른다. 그래서 사용자 요청이 하나도 없어도
     * 빈 큐는 스스로 정상으로 돌아온다.
     *
     * <p>큐가 없는 기능에 부르면 아무 일도 하지 않는다. 실패해도 던지지 않는다(다음 비움에서 다시 알린다).
     */
    void onQueueDrained(Capability capability);
}
